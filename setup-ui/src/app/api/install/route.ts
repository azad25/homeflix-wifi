import { NextRequest, NextResponse } from 'next/server';
import { exec } from 'child_process';
import { promisify } from 'util';
import fs from 'fs/promises';
import path from 'path';

const execAsync = promisify(exec);

interface InstallRequest {
  userInfo: {
    name: string;
    email: string;
    timezone: string;
    language: string;
  };
  mediaPaths: {
    primary: string;
    downloads: string;
    additional: string[];
  };
  apiKeys: {
    tmdb: string;
    opensubtitles: string;
    opensubtitlesUsername: string;
    opensubtitlesPassword: string;
    youtube: string;
  };
  systemConfig: {
    enableRedis: boolean;
    enableTorrents: boolean;
    enableSubtitles: boolean;
    hardwareAcceleration: string;
    maxConcurrentScans: number;
    cacheSize: number;
  };
}

export async function POST(request: NextRequest) {
  try {
    const config: InstallRequest = await request.json();
    
    // Create configuration files
    await createConfigFiles(config);
    
    // Create environment file
    await createEnvironmentFile(config);
    
    // Build and start Docker containers
    await buildAndStartContainers(config);
    
    // Initialize database
    await initializeDatabase(config);
    
    // Verify installation
    await verifyInstallation();
    
    return NextResponse.json({ 
      success: true, 
      message: 'HomeFlix installed successfully' 
    });
  } catch (error) {
    console.error('Installation error:', error);
    return NextResponse.json(
      { 
        success: false, 
        error: error instanceof Error ? error.message : 'Installation failed' 
      },
      { status: 500 }
    );
  }
}

async function createConfigFiles(config: InstallRequest) {
  const configDir = '/app/config';
  
  // Ensure config directory exists
  await fs.mkdir(configDir, { recursive: true });
  
  // Create user config
  const userConfig = {
    name: config.userInfo.name,
    email: config.userInfo.email,
    timezone: config.userInfo.timezone,
    language: config.userInfo.language,
    setupDate: new Date().toISOString()
  };
  
  await fs.writeFile(
    path.join(configDir, 'user.json'),
    JSON.stringify(userConfig, null, 2)
  );
  
  // Create media paths config
  const mediaConfig = {
    paths: [
      {
        path: config.mediaPaths.primary,
        name: 'Primary Media Directory',
        type: 'primary',
        active: true,
        priority: 100
      },
      {
        path: config.mediaPaths.downloads,
        name: 'Downloads Directory',
        type: 'downloads',
        active: true,
        priority: 50
      },
      ...config.mediaPaths.additional.map((path, index) => ({
        path,
        name: `Additional Path ${index + 1}`,
        type: 'additional',
        active: true,
        priority: 25
      }))
    ]
  };
  
  await fs.writeFile(
    path.join(configDir, 'media-paths.json'),
    JSON.stringify(mediaConfig, null, 2)
  );
  
  // Create system config
  const systemConfig = {
    features: {
      redis: config.systemConfig.enableRedis,
      torrents: config.systemConfig.enableTorrents,
      subtitles: config.systemConfig.enableSubtitles
    },
    performance: {
      hardwareAcceleration: config.systemConfig.hardwareAcceleration,
      maxConcurrentScans: config.systemConfig.maxConcurrentScans,
      cacheSize: config.systemConfig.cacheSize
    },
    version: '3.0.0',
    setupComplete: false
  };
  
  await fs.writeFile(
    path.join(configDir, 'system.json'),
    JSON.stringify(systemConfig, null, 2)
  );
}

