async function buildAndStartContainers(config: InstallRequest) {
  const profiles = ['production'];
  
  if (config.systemConfig.enableTorrents) {
    profiles.push('torrent');
  }
  
  // Build containers
  console.log('Building Docker containers...');
  await execAsync('docker-compose build', { cwd: '/app' });
  
  // Start containers with appropriate profiles
  console.log('Starting containers...');
  const profileArgs = profiles.map(p => `--profile ${p}`).join(' ');
  await execAsync(`docker-compose ${profileArgs} up -d`, { cwd: '/app' });
  
  // Wait for services to be ready
  console.log('Waiting for services to start...');
  await new Promise(resolve => setTimeout(resolve, 10000));
}

async function initializeDatabase(config: InstallRequest) {
  // The database will be automatically initialized by the backend service
  // We just need to wait for it to be ready and then configure it
  
  console.log('Initializing database...');
  
  // Wait for backend to be ready
  let retries = 30;
  while (retries > 0) {
    try {
      const response = await fetch('http://homeflix-backend:8252/api/health');
      if (response.ok) {
        break;
      }
    } catch (error) {
      // Service not ready yet
    }
    
    await new Promise(resolve => setTimeout(resolve, 2000));
    retries--;
  }
  
  if (retries === 0) {
    throw new Error('Backend service failed to start');
  }
  
  // Configure media paths
  for (const pathConfig of [
    { path: config.mediaPaths.primary, name: 'Primary Media Directory', type: 'primary' },
    { path: config.mediaPaths.downloads, name: 'Downloads Directory', type: 'downloads' },
    ...config.mediaPaths.additional.map((path, index) => ({
      path,
      name: `Additional Path ${index + 1}`,
      type: 'additional'
    }))
  ]) {
    try {
      await fetch('http://homeflix-backend:8252/api/admin/media-paths', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({
          path: pathConfig.path,
          name: pathConfig.name,
          path_type: pathConfig.type,
          is_active: true,
          priority: pathConfig.type === 'primary' ? 100 : pathConfig.type === 'downloads' ? 50 : 25
        }),
      });
    } catch (error) {
      console.error(`Failed to configure media path ${pathConfig.path}:`, error);
    }
  }
}

async function verifyInstallation() {
  console.log('Verifying installation...');
  
  // Check if all services are running
  const services = [
    { name: 'Backend', url: 'http://homeflix-backend:8252/api/health' },
    { name: 'Frontend', url: 'http://homeflix-frontend:3008' }
  ];
  
  for (const service of services) {
    try {
      const response = await fetch(service.url);
      if (!response.ok) {
        throw new Error(`${service.name} service is not responding correctly`);
      }
    } catch (error) {
      throw new Error(`${service.name} service verification failed: ${error}`);
    }
  }
  
  // Mark setup as complete
  const configPath = '/app/config/system.json';
  try {
    const systemConfig = JSON.parse(await fs.readFile(configPath, 'utf-8'));
    systemConfig.setupComplete = true;
    systemConfig.setupDate = new Date().toISOString();
    await fs.writeFile(configPath, JSON.stringify(systemConfig, null, 2));
  } catch (error) {
    console.error('Failed to mark setup as complete:', error);
  }
}